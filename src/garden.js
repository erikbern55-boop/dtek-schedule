// Practical seasonal horticulture tips, not lunar predictions.
// Weather-derived warnings take priority; never recommend routine watering
// during freezing or significant precipitation.
export function gardenTip(date, weather) {
  const month = Number(date.split("-")[1])
  const cold = weather?.min !== null && Number.isFinite(weather?.min) && weather.min <= 0
  const wet = Number.isFinite(weather?.rain) && weather.rain >= 65
  const windy = Number.isFinite(weather?.gust) && weather.gust >= 15
  if (cold && (month >= 3 && month <= 5 || month >= 9 && month <= 11)) {
    return "Прикрийте чутливі рослини агроволокном. Перевірте теплицю та захистіть молоді саджанці від нічного холоду."
  }
  if (windy) return "Закріпіть покривні матеріали й легкі конструкції. Перевірте гілки дерев і кріплення теплиці."
  if (month <= 2) return "Огляньте укриття багаторічників і захист молодих дерев. Не ходіть по промерзлому або надмірно мокрому ґрунту."
  if (month === 3) return "Підготуйте інструмент і перевірте насіння. Працюйте із землею лише після її відтавання та підсихання."
  if (month === 4) return "Перевірте розсаду й готовність ґрунту до посіву. Слідкуйте за прогнозом нічних похолодань."
  if (month === 5) return "Загартовуйте розсаду перед висадкою. Захищайте молоді посадки від різких змін температури."
  if (month === 6) return wet
    ? "Після дощів огляньте рослини на грибкові хвороби й забезпечте провітрювання теплиці."
    : "Огляньте грядки та мульчу. Поливайте під корінь лише за потреби, перевіривши вологість ґрунту."
  if (month === 7 || month === 8) return wet
    ? "Після рясних опадів перевірте дренаж і провітріть теплицю. Не поливайте вже мокрі грядки."
    : "Збирайте врожай і перевіряйте вологість ґрунту. За спеки поливайте вранці або ввечері."
  if (month === 9) return "Збирайте стиглий урожай, готуйте місце для озимих культур і плануйте осінню посадку дерев."
  if (month === 10) return "Приберіть уражене листя, замульчуйте пристовбурні кола і підготуйте інвентар до холодів."
  if (month === 11) return "Перевірте укриття троянд і молодих дерев. Злийте воду з вуличних шлангів перед морозами."
  return "Огляньте укриття кущів і теплицю після снігу чи вітру. Бережіть дерева від пошкодження гілок."
}
