export function sowingAdvice(date, weather, moon = null) {
  const month = Number(date?.slice(5,7))
  const season = month <= 2 || month === 12 ? "winter" : month <= 5 ? "spring" : month <= 8 ? "summer" : "autumn"
  const index = ((dayIndex(date) % 7) + 7) % 7
  const [yes, no] = sowingOptions[season][index]
  const freezing = Number.isFinite(weather?.min) && weather.min <= 0
  const snow = [71,73,75,77,85,86].includes(weather?.code)
  const coldSoil = Number.isFinite(weather?.soilTemp) && weather.soilTemp < 5
  const unsuitable = freezing || snow || coldSoil
  const outdoorRestricted = season === "winter" || (unsuitable && season !== "summer")
  const allowed = outdoorRestricted
    ? ["Мікрозелень, зелена цибуля та зелень у приміщенні.", "Підготовка насіння і субстрату для розсади.", "Зелень у теплій теплиці з достатнім світлом."][index % 3]
    : yes
  const avoid = outdoorRestricted
    ? "Посів і висадка у відкритий холодний або мерзлий ґрунт."
    : no
  // Lunar folklore is not a scientifically established planting criterion.
  const lunar = moon?.phase === "Молодик"
    ? "Молодик: за традицією планують грядки, перевіряють насіння та інструмент. Посів — за погодою."
    : "За традицією можна готувати грядки, перевіряти насіння й планувати посів. Строки визначає погода."
  return { allowed, avoid, lunar }
}
