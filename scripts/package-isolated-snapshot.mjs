// Test-only immutable snapshot package. Does not alter Telegram or production artifacts.
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const base=read('snapshots/web/today.json');
const live=read('renderer/dist/svitlopuls-live.json');
const fields=['date','group','periods','weather','generatedAt'];
const snapshot=Object.fromEntries(fields.map(k=>[k,base[k]]));
const stable=x=>Array.isArray(x)?'['+x.map(stable).join(',')+']':x&&typeof x==='object'?'{'+Object.keys(x).sort().map(k=>JSON.stringify(k)+':'+stable(x[k])).join(',')+'}':JSON.stringify(x);
const id='sha256:'+crypto.createHash('sha256').update(stable(snapshot)).digest('hex');
for(const k of ['date','group','periods','weather'])if(stable(base[k])!==stable(live[k]))throw Error('Mismatched input '+k);
if(live.canonicalGeneratedAt!==base.generatedAt)throw Error('Canonical timestamp mismatch');
const output='isolated-contract';
fs.mkdirSync(output,{recursive:true});
const canonical={...base,snapshotId:id};
const fullscreen={...live,snapshotId:id};
fs.writeFileSync(path.join(output,'today.json'),JSON.stringify(canonical,null,2));
fs.writeFileSync(path.join(output,'svitlopuls-live.json'),JSON.stringify(fullscreen,null,2));
// The test PNG is generated by the V3 renderer from the canonical schedule.
// It is NOT the independently generated Telegram today.png.
const rendered='renderer/dist/today.png';
const png=fs.readFileSync(rendered);
if(png.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw Error('Invalid V3 PNG');
const digest=crypto.createHash('sha256').update(png).digest('hex');
fs.copyFileSync(rendered,path.join(output,'today.png'));
const provenance={snapshotId:id,renderedFromSnapshot:true,renderer:'isolated V3 renderer',sourceSnapshot:'snapshots/web/today.json',pngSha256:digest,generatedAt:new Date().toISOString(),note:'Only isolated V3 PNG is attested; production Telegram PNG is NOT verified'};
fs.writeFileSync(path.join(output,'png-provenance.json'),JSON.stringify(provenance,null,2));
const verify=read(path.join(output,'png-provenance.json'));
const png2=fs.readFileSync(path.join(output,'today.png'));
if(verify.snapshotId!==id||crypto.createHash('sha256').update(png2).digest('hex')!==verify.pngSha256)throw Error('PNG provenance mismatch');
console.log(JSON.stringify({snapshotId:id,pngSha256:digest,scope:'isolated V3 only'}));
